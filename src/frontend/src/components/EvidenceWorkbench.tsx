import { Clipboard, FileText, ShieldCheck, Trash2 } from "lucide-react";
import { clearEvidenceItems, EVIDENCE_CHANGED_EVENT, readEvidenceItems, removeEvidenceItem } from "../lib/evidence";
import type { AdminConfig, EvidenceItem, Language, UserSession } from "../types";

type EvidenceWorkbenchProps = {
  config: AdminConfig;
  language: Language;
  session: UserSession | null;
};

