function c(language: Language, key: keyof typeof copy.en): string {
  return copy[language][key];
}

function display(value: unknown): string {
  if (value === null || value === undefined || value === "") {
    return "-";
  }
  return String(value);
}

function formatDate(value: string): string {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) {
    return value;
  }
  return date.toLocaleString();
}

function buildPackage(items: EvidenceItem[], config: AdminConfig, session: UserSession | null) {
  return {
    evidence_package_type: "H_UMDG_ADMIN_UI_ALPHA_UAT_PACKAGE",
    generated_at: new Date().toISOString(),
    item_count: items.length,
    environment: {
      name: config.environmentName,
      candidate_version: config.candidateVersion,
      api_base_url: config.apiBaseUrl
    },
    operator: session
      ? {
          username: session.username,
          display_name: session.displayName,
          role: session.role,
          auth_model: session.authModel ?? "local_preview"
        }
      : null,
    policy: {
      api_keys_included: false,
      raw_files_included: false,
      raw_request_payloads_included: false,
      raw_response_payloads_included: false,
      raw_failure_payloads_included: false
    },
    items: items.map((item) => item.payload)
  };
}

export function EvidenceWorkbench({ config, language, session }: EvidenceWorkbenchProps) {
  const [items, setItems] = React.useState<EvidenceItem[]>(() => readEvidenceItems());
  const [notice, setNotice] = React.useState<string | null>(null);

  const refresh = React.useCallback(() => {
    setItems(readEvidenceItems());
  }, []);

  React.useEffect(() => {
    window.addEventListener(EVIDENCE_CHANGED_EVENT, refresh);
    window.addEventListener("storage", refresh);
    return () => {
      window.removeEventListener(EVIDENCE_CHANGED_EVENT, refresh);
      window.removeEventListener("storage", refresh);
    };
  }, [refresh]);

  const successCount = items.filter((item) => item.ok === true).length;
  const traceCount = new Set(items.map((item) => item.trace_id).filter(Boolean)).size;

  const copyPackage = async () => {
    const payload = JSON.stringify(buildPackage(items, config, session), null, 2);
    await navigator.clipboard.writeText(payload);
    setNotice(c(language, "copied"));
  };

  const removeItem = (id: string) => {
    removeEvidenceItem(id);
    refresh();
  };

  const clearAll = () => {
    clearEvidenceItems();
    refresh();
  };

  return (
    <section className="panel evidence-panel" aria-labelledby="evidence-heading">
      <div className="panel-heading">
        <div>
          <p className="eyebrow">{c(language, "eyebrow")}</p>
          <h2 id="evidence-heading">{c(language, "title")}</h2>
        </div>
        <FileText size={20} />
      </div>

      <p className="workflow-description">{c(language, "lead")}</p>

      {notice ? <div className="notice-line notice-line-ok">{notice}</div> : null}

      <div className="counter-grid evidence-counter-grid">
        <div>
          <span>{c(language, "itemCount")}</span>
          <strong>{items.length}</strong>
        </div>
        <div>
          <span>{c(language, "successCount")}</span>
          <strong>{successCount}</strong>
        </div>
        <div>
          <span>{c(language, "traceCount")}</span>
          <strong>{traceCount}</strong>
        </div>
      </div>

      <div className="section-toolbar">
        <div className="transcode-heading">
          <ShieldCheck size={17} />
          <strong>{c(language, "packagePolicy")}</strong>
        </div>
        <div className="button-row">
          <button className="tool-button" type="button" disabled={!items.length} onClick={copyPackage}>
            <Clipboard size={17} />
            {c(language, "copyPackage")}
          </button>
          <button className="tool-button" type="button" disabled={!items.length} onClick={clearAll}>
            <Trash2 size={17} />
            {c(language, "clearAll")}
          </button>
        </div>
      </div>

      <dl className="task-detail-grid evidence-context-grid">
        <div>
          <dt>{c(language, "environment")}</dt>
          <dd>
            {config.environmentName} / {config.candidateVersion}
          </dd>
        </div>
        <div>
          <dt>{c(language, "operator")}</dt>
          <dd>{session ? `${session.displayName} / ${session.role}` : "-"}</dd>
        </div>
      </dl>

      {items.length ? (
        <div className="data-table evidence-table" role="table" aria-label="Saved evidence">
          <div role="row">
            <span role="columnheader">{c(language, "type")}</span>
            <span role="columnheader">{c(language, "evidenceTitle")}</span>
            <span role="columnheader">{c(language, "generated")}</span>
            <span role="columnheader">{c(language, "trace")}</span>
            <span role="columnheader">{c(language, "status")}</span>
            <span role="columnheader">{c(language, "action")}</span>
          </div>
          {items.map((item) => (
            <div role="row" key={item.id}>
              <span>{display(item.evidence_type)}</span>
              <span>{display(item.title)}</span>
              <span>{formatDate(item.generated_at)}</span>
              <span>{display(item.trace_id)}</span>
              <span>{item.ok === undefined ? "-" : item.ok ? "OK" : `HTTP ${display(item.http_status)}`}</span>
              <span>
                <button className="table-action" type="button" onClick={() => removeItem(item.id)}>
                  {c(language, "remove")}
                </button>
              </span>
            </div>
          ))}
        </div>
      ) : (
        <div className="empty-state">{c(language, "empty")}</div>
      )}
    </section>
  );
}
