function translateTextNode(node: globalThis.Text, dictionary: Record<string, string>): void {
  const value = node.nodeValue;
  if (!value) {
    return;
  }
  const trimmed = value.trim();
  if (!trimmed || !(trimmed in dictionary)) {
    return;
  }
  node.nodeValue = value.replace(trimmed, dictionary[trimmed]);
}

function translateElementAttributes(element: Element, dictionary: Record<string, string>): void {
  ["placeholder", "title", "aria-label"].forEach((name) => {
    const value = element.getAttribute(name);
    if (value && dictionary[value]) {
      element.setAttribute(name, dictionary[value]);
    }
  });
}

export function applyStaticTranslations(root: ParentNode, language: Language): MutationObserver | null {
  if (language !== "zh") {
    return null;
  }

  const translate = (node: ParentNode) => {
    const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
    let current = walker.nextNode();
    while (current) {
      translateTextNode(current as globalThis.Text, zhStaticText);
      current = walker.nextNode();
    }
    if (node instanceof Element) {
      translateElementAttributes(node, zhStaticText);
    }
    node.querySelectorAll?.("*").forEach((element) => translateElementAttributes(element, zhStaticText));
  };

  translate(root);
  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE) {
          translateTextNode(node as globalThis.Text, zhStaticText);
        } else if (node instanceof Element) {
          translate(node);
        }
      });
    });
  });
  observer.observe(root, { childList: true, subtree: true });
  return observer;
}
